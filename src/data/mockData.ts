export function createAvatarDataUri(
  fullName: string,
  roleLabel: string,
  bgStart = '#065f46',
  bgEnd = '#047857'
): string {
  const clean = fullName.replace(/^(H\.|Hj\.|Ir\.|Drs\.|Dr\.)\s*/i, '').trim();
  const parts = clean.split(/\s+/);
  const initials = ((parts[0]?.[0] || 'P') + (parts[1]?.[0] || '')).toUpperCase();
  const safeRole = roleLabel.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400" width="400" height="400">
    <defs>
      <linearGradient id="av" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgStart}"/>
        <stop offset="100%" stop-color="${bgEnd}"/>
      </linearGradient>
    </defs>
    <rect width="400" height="400" fill="url(#av)"/>
    <circle cx="200" cy="145" r="68" fill="#ffffff" fill-opacity="0.18"/>
    <path d="M85 350 C85 265 315 265 315 350 Z" fill="#ffffff" fill-opacity="0.18"/>
    <circle cx="200" cy="145" r="56" fill="#ecfdf5"/>
    <text x="200" y="163" text-anchor="middle" font-family="Arial, sans-serif" font-weight="bold" font-size="44" fill="${bgStart}">${initials}</text>
    <rect x="40" y="320" width="320" height="44" rx="22" fill="#022c22" fill-opacity="0.55"/>
    <text x="200" y="347" text-anchor="middle" font-family="Arial, sans-serif" font-weight="bold" font-size="14" fill="#a7f3d0">${safeRole}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

